#!/usr/bin/env node
// Writes src/bench-config.ts from RAYACT_BENCH_SCENARIO / RAYACT_BENCH_ROWS.
//
// `rayact build` supplies its own vite config, so a `define` in the project's
// vite.config.ts is silently dropped and the identifier survives into the
// bundle as a ReferenceError. Generating a real module is build-path agnostic.

import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const scenario = process.env.RAYACT_BENCH_SCENARIO || 'fixed';
const rowsRaw = Number.parseInt(process.env.RAYACT_BENCH_ROWS || '', 10);
const rows = Number.isFinite(rowsRaw) && rowsRaw > 0 ? rowsRaw : 10000;

const VALID = new Set(['fixed', 'variable', 'followend']);
if (!VALID.has(scenario)) {
  console.error(
    `gen-bench-config: unknown scenario ${JSON.stringify(scenario)} ` +
      `(expected one of: ${[...VALID].join(', ')})`
  );
  process.exit(1);
}

writeFileSync(
  path.join(root, 'src/bench-config.ts'),
  `// Generated by scripts/gen-bench-config.mjs — edit that, not this.\n` +
    `// \`rayact build\` runs its own vite config, so build-time \`define\` from the\n` +
    `// project vite.config.ts never reaches the bundle. A generated module is the\n` +
    `// one parameterisation channel that survives every build path.\n` +
    `export const BENCH_SCENARIO = ${JSON.stringify(scenario)};\n` +
    `export const BENCH_ROWS = ${rows};\n`
);

console.log(`gen-bench-config: scenario=${scenario} rows=${rows}`);
